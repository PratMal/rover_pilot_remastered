#!/usr/bin/env python3
"""Generate the shared protocol test vectors from the Python reference implementation.

Writes the same vectors for both test suites, so the C++ firmware and the Python drive node are checked against
each other byte for byte:
  firmware/test/test_native/vectors.h
  ros2_ws/src/rover_pilot_remastered/test/vectors.json

    python3 tools/gen_test_vectors.py          # regenerate
    python3 tools/gen_test_vectors.py --check  # exit 1 if either file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'ros2_ws' / 'src' / 'rover_pilot_remastered'))

from rover_pilot_remastered import protocol  # noqa: E402

HEADER = ROOT / 'firmware' / 'test' / 'test_native' / 'vectors.h'
JSON = ROOT / 'ros2_ws' / 'src' / 'rover_pilot_remastered' / 'test' / 'vectors.json'

COMMANDS = [
    # name, seq, estop, targets FL FR RL RR (rpm)
    ('neutral', 0, False, (0.0, 0.0, 0.0, 0.0)),
    ('forward_full', 1, False, (94.7, 94.7, 94.7, 94.7)),
    ('arc_left', 2, False, (-20.5, 60.0, -20.5, 60.0)),
    ('estop', 255, True, (0.0, 0.0, 0.0, 0.0)),
]
STATUS = protocol.DriveStatus(state=4, command_age_ms=20, pwm=(128, -255, 0, 255), rx_good=1234, rx_bad=2,
                              uptime_ms=600000, reset_reason=1, max_wheel_rpm=94.7, firmware_version=(2, 0, 0))


def build() -> dict:
    commands = []
    for name, seq, estop, targets in COMMANDS:
        payload = protocol.drive_command_payload(estop, targets)
        commands.append({'name': name, 'seq': seq, 'estop': estop, 'targets_rpm': list(targets),
                         'payload': payload.hex(), 'wire': protocol.encode_packet(protocol.TYPE_DRIVE_COMMAND, seq, payload).hex()})
    status_payload = protocol.drive_status_payload(STATUS)
    return {
        'crc_check': {'input': '123456789', 'crc': protocol.crc16(b'123456789')},
        'commands': commands,
        'status': {'seq': 7, 'payload': status_payload.hex(),
                   'wire': protocol.encode_packet(protocol.TYPE_DRIVE_STATUS, 7, status_payload).hex(),
                   'fields': {'state': STATUS.state, 'command_age_ms': STATUS.command_age_ms, 'pwm': list(STATUS.pwm),
                              'rx_good': STATUS.rx_good, 'rx_bad': STATUS.rx_bad, 'uptime_ms': STATUS.uptime_ms,
                              'reset_reason': STATUS.reset_reason, 'max_wheel_rpm': STATUS.max_wheel_rpm,
                              'firmware_version': list(STATUS.firmware_version)}},
    }


def c_bytes(hex_text: str) -> str:
    return ', '.join(f'0x{hex_text[i:i + 2]}' for i in range(0, len(hex_text), 2))


def render_header(vectors: dict) -> str:
    lines = ['// Generated by tools/gen_test_vectors.py from the Python reference protocol. Do not edit.',
             '#pragma once', '#include <stddef.h>', '#include <stdint.h>', '',
             f"static const uint16_t kCrcCheck = 0x{vectors['crc_check']['crc']:04X};  // crc16(\"123456789\")", '',
             'struct CommandVector { const char* name; uint8_t seq; bool estop; float targets[4]; const uint8_t* wire; size_t wire_len; };', '']
    for command in vectors['commands']:
        lines.append(f"static const uint8_t kWire_{command['name']}[] = {{{c_bytes(command['wire'])}}};")
    lines += ['', 'static const CommandVector kCommandVectors[] = {']
    for command in vectors['commands']:
        targets = ', '.join(f'{value:.1f}f' for value in command['targets_rpm'])
        lines.append(f"    {{\"{command['name']}\", {command['seq']}, {str(command['estop']).lower()}, {{{targets}}}, "
                     f"kWire_{command['name']}, sizeof(kWire_{command['name']})}},")
    status = vectors['status']
    lines += ['};', '', f"static const uint8_t kStatusSeq = {status['seq']};",
              f"static const uint8_t kStatusWire[] = {{{c_bytes(status['wire'])}}};", '']
    return '\n'.join(lines)


def main() -> int:
    vectors = build()
    outputs = {HEADER: render_header(vectors), JSON: json.dumps(vectors, indent=2) + '\n'}
    if '--check' in sys.argv:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f'{path.relative_to(ROOT)} is out of date; run tools/gen_test_vectors.py', file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
